-- ===== XOA OBJECT CU (neu co) - de chay lai nhieu lan =====
BEGIN
    FOR t IN (SELECT 'TABLE STUDENT_ACADEMIC' n FROM DUAL UNION ALL
              SELECT 'TABLE STUDENT'          FROM DUAL UNION ALL
              SELECT 'TABLE SUBJECT'          FROM DUAL UNION ALL
              SELECT 'TABLE SCHOOL_YEAR'      FROM DUAL UNION ALL
              SELECT 'TABLE CLASS'            FROM DUAL UNION ALL
              SELECT 'SEQUENCE SEQ_STUDENT_ACADEMIC' FROM DUAL)
    LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP ' || t.n || CASE WHEN t.n LIKE 'TABLE%' THEN ' CASCADE CONSTRAINTS' END;
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
    END LOOP;
END;
/

-- ===== TABLES =====
CREATE TABLE CLASS (
    CLASSID      VARCHAR2(20) PRIMARY KEY,
    CLASSNAME    VARCHAR2(100) NOT NULL,
    DESCRIPTION  VARCHAR2(500),
    STATUS       NUMBER(1,0) DEFAULT 1      -- 1: Active, 0: Inactive
);

CREATE TABLE SCHOOL_YEAR (
    SCHOOLYEARID   VARCHAR2(20) PRIMARY KEY,
    SCHOOLYEARNAME VARCHAR2(100) NOT NULL,
    START_YEAR     NUMBER(4,0),
    END_YEAR       NUMBER(4,0),
    STATUS         NUMBER(1,0) DEFAULT 1    -- 1: Active, 0: Inactive
);

CREATE TABLE SUBJECT (
    SUBJECTID   VARCHAR2(20) PRIMARY KEY,
    SUBJECTNAME VARCHAR2(100) NOT NULL,
    CREDITS     NUMBER(2,0) DEFAULT 0,
    DESCRIPTION VARCHAR2(500),
    STATUS      NUMBER(1,0) DEFAULT 1       -- 1: Active, 0: Inactive
);

CREATE TABLE STUDENT (
    STUDENTID        VARCHAR2(20) PRIMARY KEY,
    NAME             VARCHAR2(100) NOT NULL,
    SEX              NUMBER(1,0) DEFAULT 0,
    BIRTHOFDATE      DATE,
    BIRTHLOCAL       VARCHAR2(200),
    VNEID            VARCHAR2(12) UNIQUE,
    DATEOFISSUE      DATE,
    LOCALOFISSUE     VARCHAR2(200),
    HOMETOWN         VARCHAR2(255),
    PLACEOFRESIDENCE VARCHAR2(255),
    NUMBERPHONE      VARCHAR2(15),
    STATUS           NUMBER(1,0) DEFAULT 1  -- 1: Dang hoat dong, 0: Ngung hoat dong
);

CREATE TABLE STUDENT_ACADEMIC (
    ACADEMICID   NUMBER PRIMARY KEY,
    STUDENTID    VARCHAR2(20) NOT NULL,
    CLASSID      VARCHAR2(20),
    SCHOOLYEARID VARCHAR2(20),
    SUBJECTID    VARCHAR2(20),
    SCORE        NUMBER(4,2),
    SCORE_LETTER VARCHAR2(10),
    SEMESTER     NUMBER(2,0),
    NOTE         VARCHAR2(500),
    STATUS       NUMBER(1,0) DEFAULT 1,
    CONSTRAINT FK_ACADEMIC_STUDENT    FOREIGN KEY (STUDENTID)    REFERENCES STUDENT(STUDENTID) ON DELETE CASCADE,
    CONSTRAINT FK_ACADEMIC_CLASS      FOREIGN KEY (CLASSID)      REFERENCES CLASS(CLASSID),
    CONSTRAINT FK_ACADEMIC_SCHOOLYEAR FOREIGN KEY (SCHOOLYEARID) REFERENCES SCHOOL_YEAR(SCHOOLYEARID),
    CONSTRAINT FK_ACADEMIC_SUBJECT    FOREIGN KEY (SUBJECTID)    REFERENCES SUBJECT(SUBJECTID)
);

-- ===== SEQUENCE + TRIGGER =====
CREATE SEQUENCE SEQ_STUDENT_ACADEMIC START WITH 5 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_STUDENT_ACADEMIC_BI
BEFORE INSERT ON STUDENT_ACADEMIC
FOR EACH ROW
BEGIN
    IF :NEW.ACADEMICID IS NULL OR :NEW.ACADEMICID <= 0 THEN
        SELECT SEQ_STUDENT_ACADEMIC.NEXTVAL INTO :NEW.ACADEMICID FROM DUAL;
    END IF;
END;
